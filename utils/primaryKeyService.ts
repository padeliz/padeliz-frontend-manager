/**
 * Primary Key Service
 * Centralized service for intelligent primary key detection and management
 * Uses OpenAPI schema metadata to identify primary keys without hardcoded mappings
 */

import { ApiResourceMetadata } from '@/types/api/metadata';

/**
 * Centralized service for primary key detection and management
 * Uses OpenAPI schema metadata to intelligently identify primary keys
 */
export class PrimaryKeyService {
  /**
   * Detect primary key field from schema metadata
   * Uses multiple heuristics to identify the most likely primary key
   *
   * @param metadata - The API resource metadata containing schema information
   * @returns The field name of the primary key, or null if not found
   */
  static detectPrimaryKey(metadata: ApiResourceMetadata): string | null {
    const { swagger_schema } = metadata;
    const { properties } = swagger_schema;

    if (!properties || Object.keys(properties).length === 0) {
      return null;
    }

    // Strategy 1: Look for fields with explicit primary key indicators
    const explicitPrimaryKey = this.findExplicitPrimaryKey(properties);
    if (explicitPrimaryKey) return explicitPrimaryKey;

    // Strategy 2: Look for auto-generated ID fields (readOnly + integer + int64)
    const autoGeneratedId = this.findAutoGeneratedId(properties);
    if (autoGeneratedId) return autoGeneratedId;

    // Strategy 3: Look for fields ending with '_id' that are readOnly
    const namedIdField = this.findNamedIdField(properties);
    if (namedIdField) return namedIdField;

    // Strategy 4: Look for generic 'id' field that appears to be a primary key
    if (properties.id && this.isValidIdField(properties.id)) {
      return 'id';
    }

    return null;
  }

  /**
   * Extract primary key value from any resource object
   *
   * @param item - The resource object to extract ID from
   * @param metadata - The API resource metadata
   * @returns The primary key value, or null if not found
   */
  static extractId<T extends Record<string, any>>(
    item: T,
    metadata: ApiResourceMetadata
  ): number | null {
    const primaryKeyField = this.detectPrimaryKey(metadata);

    if (!primaryKeyField || !(primaryKeyField in item)) {
      return null;
    }

    const value = item[primaryKeyField];

    // Validate that the value is a valid ID (not null, undefined, or empty)
    if (value === null || value === undefined || value === '') {
      return null;
    }

    // Ensure the value is a number
    const numericValue = typeof value === 'string' ? parseInt(value, 10) : value;
    return isNaN(numericValue) ? null : numericValue;
  }

  /**
   * Check if a field is the primary key
   *
   * @param fieldKey - The field name to check
   * @param metadata - The API resource metadata
   * @returns True if the field is the primary key
   */
  static isPrimaryKey(fieldKey: string, metadata: ApiResourceMetadata): boolean {
    const primaryKeyField = this.detectPrimaryKey(metadata);
    return primaryKeyField === fieldKey;
  }

  /**
   * Get all potential primary key candidates from the schema
   * Useful for debugging and validation
   *
   * @param metadata - The API resource metadata
   * @returns Array of field names that could be primary keys
   */
  static getPrimaryKeyCandidates(metadata: ApiResourceMetadata): string[] {
    const { swagger_schema } = metadata;
    const { properties } = swagger_schema;
    const candidates: string[] = [];

    if (!properties) return candidates;

    Object.entries(properties).forEach(([key, field]) => {
      if (this.isValidIdField(field)) {
        candidates.push(key);
      }
    });

    return candidates;
  }

  /**
   * Find fields with explicit primary key indicators in their metadata
   * Looks for keywords in description, title, or other metadata fields
   */
  private static findExplicitPrimaryKey(properties: Record<string, any>): string | null {
    for (const [key, field] of Object.entries(properties)) {
      if (!this.isValidIdField(field)) continue;

      const description = field.description?.toLowerCase() || '';
      const title = field.title?.toLowerCase() || '';

      const primaryKeyIndicators = [
        'primary key',
        'unique identifier',
        'id',
        'identifier'
      ];

      const hasExplicitIndicator = primaryKeyIndicators.some(indicator =>
        description.includes(indicator) || title.includes(indicator)
      );

      if (hasExplicitIndicator) {
        return key;
      }
    }
    return null;
  }

  /**
   * Find auto-generated ID fields
   * Looks for fields that are readOnly, integer, int64, and contain 'id' in the name
   */
  private static findAutoGeneratedId(properties: Record<string, any>): string | null {
    for (const [key, field] of Object.entries(properties)) {
      if (
        field.readOnly &&
        field.type === 'integer' &&
        field.format === 'int64' &&
        (key.includes('id') || key === 'id')
      ) {
        return key;
      }
    }
    return null;
  }

  /**
   * Find named ID fields ending with '_id'
   * Looks for fields ending with '_id' that are readOnly and valid ID fields
   */
  private static findNamedIdField(properties: Record<string, any>): string | null {
    for (const [key, field] of Object.entries(properties)) {
      if (
        key.endsWith('_id') &&
        field.readOnly &&
        this.isValidIdField(field)
      ) {
        return key;
      }
    }
    return null;
  }

  /**
   * Validate if a field definition represents a valid ID field
   * Checks type, format, and other characteristics
   */
  private static isValidIdField(field: any): boolean {
    if (!field || typeof field !== 'object') return false;

    // Must be an integer type
    if (field.type !== 'integer') return false;

    // Should be int64 format (most common for IDs)
    if (field.format && field.format !== 'int64') return false;

    // Should not be nullable (primary keys are typically required)
    if (field.nullable === true) return false;

    return true;
  }
}
